export function translate(text, language = 'en') {
  if (language !== 'ta' || typeof text !== 'string') return text
  return tamil[text] ?? commonTamilTranslations[text] ?? text
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return window.localStorage.getItem(LANGUAGE_KEY) === 'ta' ? 'ta' : 'en'
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    document.documentElement.lang = language === 'ta' ? 'ta' : 'en'
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, t: (text) => translate(text, language) }), [language])
  return createElement(LanguageContext.Provider, { value }, children)
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

export function LanguageSelector({ className = '' }) {
  const { language, setLanguage, t } = useLanguage()
  function selectLanguage(event) {
    const nextLanguage = event.target.value
    try {
      window.localStorage.setItem(LANGUAGE_KEY, nextLanguage)
    } catch {
      // The selected language remains active for this page when storage is unavailable.
    }
    setLanguage(nextLanguage)
  }

  return createElement(
    'label',
    { className: `language-selector ${className}`.trim() },
    createElement('span', { 'aria-hidden': 'true' }, '◎'),
    createElement('span', { className: 'sr-only' }, t('Language')),
    createElement(
      'select',
      { 'aria-label': t('Language'), value: language, onChange: selectLanguage },
      createElement('option', { value: 'en' }, 'English'),
      createElement('option', { value: 'ta' }, language === 'ta' ? 'தமிழ்' : 'Tamil'),
    ),
  )
}
